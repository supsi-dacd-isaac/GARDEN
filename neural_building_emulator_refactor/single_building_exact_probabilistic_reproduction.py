"""Fit the production probabilistic closed-loop architecture to one building.

This is a counterproof for architecture-level overdispersion. It reconstructs
the exact model class and objective settings from an existing production
artifact, removes cross-building information by centering one fixed metadata
vector to zero, and fits only temporally split trajectories from one EGID.
Annual confidence bands are generated by the model's real xi, process-noise,
HP-mode and active-power sampling paths, not by optimization restarts.
"""

